LENGTH_SPECS = {
    "short": {"min_words": 180, "max_words": 220, "min_chars": 1300, "max_chars": 1600},
    "medium": {"min_words": 380, "max_words": 420, "min_chars": 2700, "max_chars": 3000},
    "long": {"min_words": 750, "max_words": 800, "min_chars": 5400, "max_chars": 6000},
}

SYSTEM_PROMPT = """
Ты — талантливый профессиональный автор поздравлений в стихах, известный тем, что каждый твой текст \
уникален и не похож на шаблонные поздравления из интернета. Твоя задача — писать тёплые, живые, оригинальные, \
захватывающие внимание стихотворения, которые звучат так, будто их написал близкий человек, а не машина и не \
копирайтер на потоке.

ГЛАВНЫЙ ПРИОРИТЕТ: стихотворение не должно быть банальным. Оно должно выделяться на фоне тысяч типовых \
поздравлений. Это самое важное правило, важнее всех остальных.

ПРАВИЛА:

1. КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО использовать избитые рифмы и шаблонные фразы: "день рожденья — веселья", \
"года летят — счастья хранят", "свечи горят — мечты говорят", "судьба — судьба", "беда — беда" и любые \
похожие клише. Если ловишь себя на том, что хочешь написать что-то подобное — остановись и найди более \
свежую, неожиданную рифму и образ.

2. Проявляй настоящую креативность: экспериментируй с ритмом и формой (не обязательно четырёхстопный \
хорей!), находи неочевидные сравнения, необычные метафоры и образы. Обязательно используй детали, которые дал \
заказчик (факты, забавные истории), — вплетай их органично в стихотворение, а не просто перечисляй списком.

3. Если указаны "особые факты" — используй их для персонализации, чтобы стихотворение ощущалось написанным \
именно для этого человека, а не для кого угодно. Детали должны быть узнаваемы адресатом.

4. Если указаны "секреты или забавные истории" — обыграй их с мягким, добрым юмором. Юмор должен быть \
дружелюбным, тёплым, вызывающим улыбку, а не смех НАД человеком. Ты должен искать в любой детали, даже на \
первый взгляд неловкой, что-то милое и обаятельное.

ВАЖНО: если деталь в "секретах" звучит негативно, грубо или обидно (например, критика характера, недостатков \
человека) — НЕ используй её напрямую и НЕ транслируй грубость. Вместо этого мягко переформулируй в позитивном \
или юмористическом ключе, превращая недостаток в милую особенность. Смысл детали сохраняй, но подавай его так, \
чтобы адресату было приятно и смешно, а не обидно.

5. Учитывай возраст адресата:
   - Дети — простой, радостный, звонкий стиль, лёгкие рифмы, короткие строки
   - Подростки — живой, современный язык, интересные образы, без "взрослого" пафоса
   - Взрослые — стиль в соответствии с выбранным тоном, более сложные метафоры
   - Пожилые люди — тёплый, уважительный, душевный тон, без излишней фамильярности

6. Тон поздравления, который выбрал заказчик, должен быть выражен максимально ярко и точно через образность, \
ритм и выбор слов:
{tone_description}

7. Строго соблюдай требуемый объём стихотворения: {length_lines} строк (примерно {length_words} слов). Это \
обязательное техническое требование, соблюдай его точно.

8. Выбери оптимальный размер и схему рифмовки (не обязательно классические!): можешь использовать перекрёстную \
рифму (АБАБ), парную (ААББ), опоясывающую (АББА), свободный стих или даже асонанс — главное, чтобы звучало \
естественно и красиво.

9. В конце стихотворения обязательно добавь подпись, которую указал заказчик, оформленную на новой строке, \
например:

С наилучшими пожеланиями, твоя сестра Оля

10. Пиши только само стихотворение, без вступлений вроде "Вот вариант поздравления:" и без пояснений или \
комментариев после текста.

11. Стихотворение должно быть уникальным и написанным будто специально для этого конкретного человека, а не \
для абстрактного адресата.
"""


def build_first_prompt(data: dict) -> tuple[str, str]:
    """Возвращает (system_prompt, user_prompt)"""
    tone_desc = TONE_DESCRIPTIONS.get(data.get("tone"), "")
    length_spec = LENGTH_SPECS.get(data.get("length"), LENGTH_SPECS["medium"])

    system = SYSTEM_PROMPT.format(
        tone_description=tone_desc,
        length_sentences=length_spec["sentences"],
        length_words=length_spec["words"],
    )

    user = f"""
Напиши поздравление в прозе по следующим данным:

Имя именинника: {data.get('name')}
Возраст: {data.get('age')}
Кем приходится заказчику: {data.get('relationship')}
Повод: {data.get('occasion')}
Особые факты: {data.get('details')}
Секреты/забавные истории (обыграть мягким юмором, смягчить если звучит негативно): {data.get('secrets')}
Подпись в конце: {data.get('signature')}
"""

    return system, user


def build_second_prompt(data: dict, first_variant: str) -> tuple[str, str]:
    system, user = build_first_prompt(data)

    addition = f"""

Ты уже написал один вариант поздравления, вот он:

---
{first_variant}
---

Теперь напиши ВТОРОЙ вариант поздравления по тем же данным, но он должен быть ПРИНЦИПИАЛЬНО ДРУГИМ:
- другое начало (не используй тот же заход, что в первом варианте)
- другая структура текста
- другие слова и эпитеты, минимум повторов лексики из первого варианта
- можно раскрыть те же факты и детали, но под другим углом, с другими сравнениями

При этом второй вариант должен быть таким же качественным, живым и не банальным, как первый, и соответствовать \
всем правилам выше.
"""

    return system, user + addition


def count_words(text: str) -> int:
    return len(text.split())


async def generate_single_variant(system_prompt: str, user_prompt: str) -> str:
    async with httpx.AsyncClient(timeout=90.0) as client:
        response = await client.post(
            f"{GPTUNNEL_BASE_URL}/messages",
            headers={
                "Authorization": GPTUNNEL_API_KEY,
                "Content-Type": "application/json",
            },
            json={
                "model": CLAUDE_MODEL,
                "max_tokens": 2048,
                "system": system_prompt,
                "messages": [
                    {"role": "user", "content": user_prompt}
                ],
            },
        )
        response.raise_for_status()
        data = response.json()
        return data["content"][0]["text"].strip()


async def generate_with_length_check(
    system_prompt: str, user_prompt: str, length_key: str, max_attempts: int = 2
) -> str:
    spec = LENGTH_SPECS.get(length_key, LENGTH_SPECS["medium"])
    text = await generate_single_variant(system_prompt, user_prompt)

    attempts = 0
    while attempts < max_attempts:
        word_count = count_words(text)

        if spec["min"] <= word_count <= spec["max"]:
            return text

        if word_count < spec["min"]:
            correction = f"\n\nТекст получился слишком коротким ({word_count} слов). " \
                          f"Перепиши его, сохранив смысл и стиль, но увеличь объём до {spec['words']}."
        else:
            correction = f"\n\nТекст получился слишком длинным ({word_count} слов). " \
                          f"Перепиши его, сохранив смысл и стиль, но сократи объём до {spec['words']}."

        text = await generate_single_variant(system_prompt, user_prompt + correction)
        attempts += 1

    return text


async def generate_greeting(data: dict) -> list[str]:
    length_key = data.get("length", "medium")

    system_1, user_1 = build_first_prompt(data)
    variant_1 = await generate_with_length_check(system_1, user_1, length_key)

    system_2, user_2 = build_second_prompt(data, variant_1)
    variant_2 = await generate_with_length_check(system_2, user_2, length_key)

    return [variant_1, variant_2]